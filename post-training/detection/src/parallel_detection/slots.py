"""One-pass set detection on a frozen Moondream 2: slots, boxes and masked-diffusion labels.

After the image prefix, the decoder reads `slots` blocks of 1 + `label_tokens`
positions in a single forward pass. All slot positions see the image and each other.

- The first position of a block is a learned query. Its final hidden state gives an
  objectness logit (the slot may be "nothing") and a box as four regressed coordinates.
- The remaining positions are the slot's label, generated by masked discrete diffusion:
  every position starts as a mask embedding and the model's own vocabulary head
  predicts its token. One pass with everything masked is the one-step sampler; further
  passes keep the most confident tokens and predict the rest again.

The backbone weights stay frozen. Low-rank adapters act only at slot positions, so the
image prefix and every existing skill of the model are unchanged.
"""

import math

import torch
import torch.nn.functional as F
from scipy.optimize import linear_sum_assignment
from torch import nn

PREFIX = 730  # BOS + 729 image tokens
HEADS = 32


class LowRank(nn.Module):
    def __init__(self, inputs, outputs, rank):
        super().__init__()
        self.down = nn.Linear(inputs, rank, bias=False)
        self.up = nn.Linear(rank, outputs, bias=False)
        nn.init.zeros_(self.up.weight)

    def forward(self, x):
        return self.up(self.down(x))


def block_forward(block, x, positions, freqs, rotate, prefix=None, adapter=None):
    """One Moondream decoder block on x [B, S, D]; returns the new x and this span's keys/values.

    `prefix` is (keys, values) of earlier positions that every position of x may attend
    to; positions of x attend to each other without a mask. The frozen weights compute
    in their own precision; x and the adapters keep the precision of x.
    """
    batch, length, dim = x.shape
    frozen = block.attn.qkv.weight.dtype
    normed = F.layer_norm(x, (dim,), block.ln.weight.to(x.dtype), block.ln.bias.to(x.dtype))
    qkv = block.attn.qkv(normed.to(frozen))
    if adapter is not None:
        qkv = (qkv + adapter["qkv"](normed)).to(frozen)
    q, k, v = (t.view(batch, length, HEADS, dim // HEADS).transpose(1, 2) for t in qkv.chunk(3, -1))
    q, k = rotate(q, freqs, positions, HEADS), rotate(k, freqs, positions, HEADS)
    keys, values = k, v
    if prefix is not None:
        keys, values = torch.cat([prefix[0], k], dim=2), torch.cat([prefix[1], v], dim=2)
    mixed = F.scaled_dot_product_attention(q, keys, values)
    mixed = mixed.transpose(1, 2).reshape(batch, length, dim)
    attended = block.attn.proj(mixed).to(x.dtype)
    hidden = block.mlp.fc1(normed.to(frozen)).to(x.dtype)
    if adapter is not None:
        attended = attended + adapter["proj"](mixed.to(x.dtype))
        hidden = hidden + adapter["fc1"](normed)
    hidden = F.gelu(hidden, approximate="tanh")
    out = block.mlp.fc2(hidden.to(frozen)).to(x.dtype)
    if adapter is not None:
        out = out + adapter["fc2"](hidden)
    return x + attended + out, (k, v)


@torch.no_grad()
def prefix_cache(text, embeddings, rotate):
    """Keys and values of the image prefix for a batch of [B, PREFIX, D] input embeddings."""
    positions = torch.arange(embeddings.size(1), device=embeddings.device)
    x, cache = embeddings, []
    for block in text.blocks:
        x, kv = block_forward(block, x, positions, text.freqs_cis, rotate)
        cache.append(kv)
    return cache


class SlotHead(nn.Module):
    """The trainable parts: slot queries, label inputs, adapters and the box/objectness heads."""

    def __init__(self, text, slots=32, label_tokens=3, rank=16):
        super().__init__()
        dim, ff = text.wte.size(1), text.blocks[0].mlp.fc1.out_features
        self.slots, self.label_tokens = slots, label_tokens
        embeddings = text.wte.detach().float()
        scale = embeddings.std().item()
        self.queries = nn.Parameter(torch.randn(slots, dim) * scale)
        self.mask = nn.Parameter(embeddings.mean(0).clone())
        self.label_position = nn.Parameter(torch.randn(label_tokens, dim) * scale * 0.1)
        self.adapters = nn.ModuleList(
            nn.ModuleDict(
                {
                    "qkv": LowRank(dim, 3 * dim, rank),
                    "proj": LowRank(dim, dim, rank),
                    "fc1": LowRank(dim, ff, rank),
                    "fc2": LowRank(ff, dim, rank),
                }
            )
            for _ in text.blocks
        )
        self.box = nn.Sequential(nn.Linear(dim, dim), nn.GELU(), nn.Linear(dim, 4))
        self.objectness = nn.Linear(dim, 1)

    def forward(self, text, cache, rotate, revealed=None, reveal=None):
        """Return objectness logits [B, K], boxes [B, K, 4] (cx, cy, w, h in 0..1) and
        label logits [B, K, T, vocabulary].

        `revealed` [B, K, T] holds token ids and `reveal` marks the label positions that
        are given to the model instead of the mask.
        """
        batch = cache[0][0].size(0)
        labels = (self.mask + self.label_position).expand(batch, self.slots, -1, -1)
        if reveal is not None:
            known = text.wte[revealed].float() + self.label_position
            labels = torch.where(reveal.unsqueeze(-1), known, labels)
        # Label positions carry their slot's query so that they bind to that slot.
        labels = labels + self.queries[None, :, None, :]
        queries = self.queries[None, :, None, :].expand(batch, -1, -1, -1)
        x = torch.cat([queries, labels], dim=2).flatten(1, 2)
        positions = PREFIX + torch.arange(x.size(1), device=x.device)
        for block, kv, adapter in zip(text.blocks, cache, self.adapters, strict=True):
            x, _ = block_forward(block, x, positions, text.freqs_cis, rotate, kv, adapter)
        x = F.layer_norm(x, (x.size(-1),), text.post_ln.weight.float(), text.post_ln.bias.float())
        x = x.view(batch, self.slots, 1 + self.label_tokens, -1)
        logits = text.lm_head(x[:, :, 1:].to(text.lm_head.weight.dtype)).float()
        return self.objectness(x[:, :, 0]).squeeze(-1), self.box(x[:, :, 0]).sigmoid(), logits


def to_corners(boxes):
    cx, cy, w, h = boxes.unbind(-1)
    return torch.stack([cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2], dim=-1)


def generalized_iou(a, b):
    """Pairwise generalized IoU of corner boxes a [N, 4] and b [M, 4]."""
    area_a = (a[:, 2] - a[:, 0]).clamp(min=0) * (a[:, 3] - a[:, 1]).clamp(min=0)
    area_b = (b[:, 2] - b[:, 0]).clamp(min=0) * (b[:, 3] - b[:, 1]).clamp(min=0)
    inter = torch.min(a[:, None, 2:], b[None, :, 2:]) - torch.max(a[:, None, :2], b[None, :, :2])
    inter = inter.clamp(min=0).prod(-1)
    union = area_a[:, None] + area_b[None, :] - inter
    hull = torch.max(a[:, None, 2:], b[None, :, 2:]) - torch.min(a[:, None, :2], b[None, :, :2])
    hull = hull.clamp(min=0).prod(-1)
    iou = inter / union.clamp(min=1e-9)
    return iou - (hull - union) / hull.clamp(min=1e-9), iou


WEIGHTS = {"l1": 5.0, "giou": 2.0, "objectness": 1.0, "label": 1.0, "empty": 0.1}


def match(objectness, boxes, log_probs, truth_boxes, truth_tokens):
    """Hungarian matching of one image's slots to its truth objects.

    Returns slot indices and truth indices. The cost combines box distance, overlap,
    objectness and the label's negative log-likelihood.
    """
    giou, _ = generalized_iou(to_corners(boxes), to_corners(truth_boxes))
    label = -log_probs[:, None, :, :].expand(-1, truth_tokens.size(0), -1, -1)
    label = label.gather(-1, truth_tokens[None, :, :, None].expand(boxes.size(0), -1, -1, -1))
    cost = (
        WEIGHTS["l1"] * torch.cdist(boxes, truth_boxes, p=1)
        - WEIGHTS["giou"] * giou
        - WEIGHTS["objectness"] * objectness.sigmoid()[:, None]
        + WEIGHTS["label"] * label.squeeze(-1).mean(-1)
    )
    rows, cols = linear_sum_assignment(cost.detach().float().cpu().numpy())
    return torch.as_tensor(rows, device=boxes.device), torch.as_tensor(cols, device=boxes.device)


def set_loss(objectness, boxes, logits, targets):
    """Losses for a batch; `targets` is a list of (boxes [n, 4] cxcywh, tokens [n, T]).

    Unmatched slots are pushed toward "nothing" with a small weight: the labels name
    some objects in the image, not every object.
    Returns the loss terms, and the matching as (batch, slot, truth) index tensors.
    """
    log_probs = logits.log_softmax(-1)
    batch_index, slot_index, truth_boxes, truth_tokens = [], [], [], []
    for b, (t_boxes, t_tokens) in enumerate(targets):
        rows, cols = match(objectness[b], boxes[b], log_probs[b], t_boxes, t_tokens)
        batch_index.append(torch.full_like(rows, b))
        slot_index.append(rows)
        truth_boxes.append(t_boxes[cols])
        truth_tokens.append(t_tokens[cols])
    batch_index, slot_index = torch.cat(batch_index), torch.cat(slot_index)
    truth_boxes, truth_tokens = torch.cat(truth_boxes), torch.cat(truth_tokens)
    matched = torch.zeros_like(objectness)
    matched[batch_index, slot_index] = 1.0
    weight = torch.where(matched.bool(), 1.0, WEIGHTS["empty"])
    predicted = boxes[batch_index, slot_index]
    giou, iou = generalized_iou(to_corners(predicted), to_corners(truth_boxes))
    terms = {
        "objectness": F.binary_cross_entropy_with_logits(objectness, matched, weight),
        "l1": F.l1_loss(predicted, truth_boxes),
        "giou": 1 - giou.diagonal().mean(),
        "label": F.nll_loss(
            log_probs[batch_index, slot_index].flatten(0, 1), truth_tokens.flatten()
        ),
    }
    stats = {
        "matched_iou": iou.diagonal().mean().item(),
        "label_exact": (logits[batch_index, slot_index].argmax(-1) == truth_tokens)
        .all(-1)
        .float()
        .mean()
        .item(),
    }
    return terms, (batch_index, slot_index, truth_tokens), stats


def total(terms):
    return sum(WEIGHTS[name] * value for name, value in terms.items())


def diffusion_loss(head, text, cache, rotate, matching, generator):
    """Masked-diffusion training step for the labels of matched slots.

    Each matched slot gets a masking ratio drawn uniformly; revealed positions are
    given their true token and the loss is taken on the positions still masked.
    """
    batch_index, slot_index, truth_tokens = matching
    batch = cache[0][0].size(0)
    shape = (batch, head.slots, head.label_tokens)
    revealed = torch.zeros(shape, dtype=torch.long, device=truth_tokens.device)
    reveal = torch.zeros(shape, dtype=torch.bool, device=truth_tokens.device)
    ratio = torch.rand(truth_tokens.size(0), 1, generator=generator, device=truth_tokens.device)
    draw = torch.rand(truth_tokens.shape, generator=generator, device=truth_tokens.device)
    revealed[batch_index, slot_index] = truth_tokens
    reveal[batch_index, slot_index] = draw > ratio
    _, _, logits = head(text, cache, rotate, revealed, reveal)
    masked = ~reveal[batch_index, slot_index]
    if not masked.any():
        return logits.sum() * 0
    return F.cross_entropy(logits[batch_index, slot_index][masked], truth_tokens[masked])


@torch.no_grad()
def sample_labels(head, text, cache, rotate, steps):
    """Sample labels in `steps` passes; returns objectness, boxes, tokens and token confidence.

    Each pass after the first reveals the most confident predictions so far (an equal
    share of positions per pass) and predicts the remaining positions again.
    """
    revealed = reveal = None
    for step in range(steps):
        objectness, boxes, logits = head(text, cache, rotate, revealed, reveal)
        confidence, tokens = logits.softmax(-1).max(-1)
        if reveal is not None:
            tokens = torch.where(reveal, revealed, tokens)
            confidence = torch.where(reveal, torch.ones_like(confidence), confidence)
        if step + 1 < steps:
            keep = math.ceil(head.label_tokens * (step + 1) / steps)
            order = confidence.argsort(-1, descending=True)
            reveal = torch.zeros_like(tokens, dtype=torch.bool).scatter(-1, order[..., :keep], True)
            revealed = tokens
    return objectness, boxes, tokens, confidence
