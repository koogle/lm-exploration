"""Full pinned Python files supplement the user's preferred repository snapshots."""

from .python_experiment import canonical_repo, category

REPOSITORY = "codeparrot/codeparrot-clean-train"
REVISION = "3e6ab65f2864931e041f6a82db9b5a6ec2b71ab4"
LICENSES = {"mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "isc", "unlicense", "cc0-1.0"}


def select_document(record):
    if not isinstance(record, dict):
        return None, "malformed_record"
    text, path, parent = record.get("content"), record.get("path"), record.get("repo_name")
    if not isinstance(parent, str) or "/" not in parent or not isinstance(path, str):
        return None, "missing_file_provenance"
    if not isinstance(record.get("license"), str) or record["license"] not in LICENSES:
        return None, "unresolved_or_unselected_license"
    if record.get("autogenerated") is True:
        return None, "upstream_generated_flag"
    name, reason = category(path, text)
    if name not in ("python_implementation", "python_tests_examples"):
        return None, reason or "not_python_source"
    return (
        text,
        name,
        canonical_repo(parent),
        {
            "origin": "supplemental_python_file",
            "dataset": REPOSITORY,
            "revision": REVISION,
            "repository": parent,
            "path": path,
            "license": record["license"],
            "upstream_hash": record.get("hash"),
        },
    ), None
