"""Supervised fine-tuning datasets: prompts paired with complete written answers.

What SFT trains: each example is one prompt and one full answer written by people or
another model (never generated by the model being trained). The model reads
`BOS + prompt` and is trained by teacher-forced next-token prediction on every token of
`answer + EOS`; prompt tokens carry no loss. One example is one sequence, never
truncated.

A dataset is a JSONL file of rows. `SFTDataset` holds everything shared: required
fields, train/validation leak checks, encoding and the answer-only label mask. A
subclass sets `FORMAT` and `FIELDS` and says how a row becomes a prompt and an answer.
"""

import hashlib
import json
from pathlib import Path

from training_data.subword import BOS_TOKEN_ID, EOS_TOKEN_ID, LOSS_IGNORE_INDEX

# Fields every row carries; subclasses add their own.
COMMON_FIELDS = ("id", "group", "split", "source", "license")


class SFTDataset:
    FORMAT = ""
    FIELDS = ()

    def prompt(self, row):
        """The text the model reads before answering."""
        raise NotImplementedError

    def answer(self, row):
        """The complete text the model is trained to write; EOS follows it."""
        raise NotImplementedError

    def bucket(self, row):
        """The group validation loss is reported for."""
        raise NotImplementedError

    def fingerprints(self, row):
        """Texts that may not appear in both splits (normalized before comparison)."""
        return ()

    def check(self, row):
        """Format-specific validation of one row; raise ValueError to reject it."""

    def check_splits(self, splits):
        """Validation of the encoded splits as a whole."""

    def encode(self, row, tokenizer, context):
        """Inputs `x`, targets `y` with the prompt masked, and the row's bucket."""
        prefix = [BOS_TOKEN_ID] + tokenizer.encode(self.prompt(row), add_special_tokens=False).ids
        answer = tokenizer.encode(self.answer(row), add_special_tokens=False).ids
        answer.append(EOS_TOKEN_ID)
        if len(prefix) + len(answer) - 1 > context:
            raise ValueError(f"Example {row['id']} exceeds context; refusing to truncate it")
        tokens = prefix + answer
        labels = [LOSS_IGNORE_INDEX] * len(prefix) + answer
        return {"id": row["id"], "bucket": self.bucket(row), "x": tokens[:-1], "y": labels[1:]}

    def prepare(self, path, tokenizer, context):
        """Encoded train/validation splits and the file's SHA256; rejects split leaks."""
        raw = Path(path).read_bytes()
        splits = {"train": [], "validation": []}
        ids, groups, texts = set(), {}, {}
        for line in raw.decode().splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            for key in (*COMMON_FIELDS, *self.FIELDS):
                if not isinstance(row.get(key), str) or not row[key].strip():
                    raise ValueError(f"Missing nonempty string: {key}")
            split = row["split"]
            if split not in splits or row["id"] in ids:
                raise ValueError("Invalid split or duplicate ID")
            ids.add(row["id"])
            # A group is one source unit (repository, original problem) and all its rows.
            if groups.setdefault(row["group"], split) != split:
                raise ValueError("Group crosses train/validation")
            for text in self.fingerprints(row):
                if texts.setdefault(" ".join(text.split()).lower(), split) != split:
                    raise ValueError("Duplicate text crosses train/validation")
            self.check(row)
            splits[split].append(self.encode(row, tokenizer, context))
        if not all(splits.values()):
            raise ValueError("Both train and validation examples are required")
        self.check_splits(splits)
        return splits, hashlib.sha256(raw).hexdigest()
