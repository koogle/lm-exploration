import tempfile
import unittest
from pathlib import Path

from training_data.python_code_supplement import select_document
from training_data.python_experiment import Corpus
from training_data.python_snapshot import merge_code

TEXT = '# Preserve this implementation comment.\ndef add(a, b):\n    """Add two arguments."""\n    return a + b\n'


class CodeSupplementTests(unittest.TestCase):
    def test_file_category_license_and_malformed_fields(self):
        row = {
            "repo_name": "org/repo",
            "path": "tests/test_add.py",
            "content": TEXT,
            "license": "mit",
        }
        result, reason = select_document(row)
        self.assertIsNone(reason)
        self.assertEqual(result[:3], (TEXT, "python_tests_examples", "org/repo"))
        row["license"] = {}
        self.assertEqual(select_document(row)[1], "unresolved_or_unselected_license")
        row["license"] = "mit"
        row["autogenerated"] = True
        self.assertEqual(select_document(row)[1], "upstream_generated_flag")

    def test_collected_repository_snapshot_wins_over_supplement(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            corpus = Corpus(root / "main")
            corpus.db.execute("INSERT INTO repositories VALUES('org/repo', 'train', 'pinned')")
            corpus.report("test")
            corpus.db.close()
            shard = Corpus(root / "supplement" / "shard")
            shard.add(TEXT, "python_implementation", "org/repo", {}, split="train")
            shard.report("test")
            shard.db.close()
            (root / "supplement" / "shard" / "complete.json").write_text("{}")
            result = merge_code(root / "main", root / "supplement")
            self.assertEqual(
                result["categories"]["python_implementation"]["unique_train_targets"], 0
            )
            self.assertEqual(result["rejections"]["older_collected_repository_version"], 1)


if __name__ == "__main__":
    unittest.main()
